#!/usr/bin/env node
// Regenerates src/app/core/api/contract/schema.d.ts from the vendored OpenAPI snapshot.
//
//   node scripts/generate-contract.mjs           write schema.d.ts
//   node scripts/generate-contract.mjs --check   exit 1 if the committed schema.d.ts differs
//
// The snapshot (src/app/core/api/contract/openapi.json) is a byte copy of the backend's
// docs/openapi/openapi.json; its provenance is in src/app/core/api/contract/README.md. It is the
// only source: the contract is never fetched from a live /api-docs here.
//
// The generator is openapi-typescript, which emits a declaration file and no runtime code by
// construction (ADR 0002). It is installed in tools/contract/, apart from the application,
// because openapi-typescript 7.13.x declares a peer `typescript ^5.x` and the application pins
// TypeScript 6.0.x. Install it once with `npm run contract:install`.

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CONTRACT_DIR = resolve(root, 'src/app/core/api/contract');
export const SNAPSHOT = resolve(CONTRACT_DIR, 'openapi.json');
export const SCHEMA_DTS = resolve(CONTRACT_DIR, 'schema.d.ts');
export const PROVENANCE = resolve(CONTRACT_DIR, 'README.md');
const TOOLS_DIR = resolve(root, 'tools/contract');
const GENERATOR = resolve(TOOLS_DIR, 'node_modules/openapi-typescript/bin/cli.js');

const HEADER = [
  '// GENERATED by `npm run contract` from openapi.json in this folder. Never edit by hand.',
  '// Types only: this file emits no JavaScript (ADR 0002). Features import the aliases of',
  '// models.ts, not `components["schemas"]` directly.',
  '',
].join('\n');

/** The generator's version, read from its installed package, or null when it is not installed. */
export function generatorVersion() {
  const manifest = resolve(TOOLS_DIR, 'node_modules/openapi-typescript/package.json');
  return existsSync(manifest) ? JSON.parse(readFileSync(manifest, 'utf8')).version : null;
}

/** schema.d.ts as a regeneration from the vendored snapshot would write it. */
export function regenerate() {
  if (!existsSync(GENERATOR)) {
    throw new Error(
      `openapi-typescript is not installed in ${relative(root, TOOLS_DIR)}. Run \`npm run contract:install\`.`,
    );
  }
  const result = spawnSync(process.execPath, [GENERATOR, SNAPSHOT], {
    cwd: TOOLS_DIR,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.status !== 0) {
    throw new Error(`openapi-typescript failed (exit ${result.status}):\n${result.stderr}`);
  }
  return HEADER + result.stdout;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const generated = regenerate();
  if (process.argv.includes('--check')) {
    const committed = existsSync(SCHEMA_DTS) ? readFileSync(SCHEMA_DTS, 'utf8') : '';
    if (committed !== generated) {
      console.error(
        `${relative(root, SCHEMA_DTS)} differs from a regeneration of ${relative(root, SNAPSHOT)}. ` +
          'Run `npm run contract` and commit the result; never edit schema.d.ts by hand.',
      );
      process.exit(1);
    }
    console.log(`${relative(root, SCHEMA_DTS)} matches the vendored snapshot.`);
  } else {
    writeFileSync(SCHEMA_DTS, generated);
    console.log(
      `Wrote ${relative(root, SCHEMA_DTS)} with openapi-typescript ${generatorVersion()}.`,
    );
  }
}
